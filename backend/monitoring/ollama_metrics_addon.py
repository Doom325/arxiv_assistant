import json
import logging
from mitmproxy import http
from prometheus_client import Counter, Histogram, Gauge, start_http_server

# Prometheus Metrics Definition
REQUESTS = Counter("ollama_requests_total", "Total Ollama classification requests", ["model", "status"])
TOKENS = Counter("ollama_tokens_total", "Total tokens generated by Ollama", ["model"])
LATENCY = Histogram(
    "ollama_request_latency_seconds",
    "Request latency in seconds",
    ["model"],
    buckets=[0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 30.0, 60.0, 120.0]
)
ACTIVE = Gauge("ollama_active_requests", "Currently active requests routing to Ollama")

class OllamaMetricsAddon:
    def __init__(self):
        # Start Prometheus metrics server natively on initialization
        start_http_server(8765)
        logging.info("Mitmproxy Prometheus metrics server started on port 8765")

    def request(self, flow: http.HTTPFlow):
        # We only care about generation/chat endpoints
        if "/api/chat" in flow.request.path or "/api/generate" in flow.request.path:
            ACTIVE.inc()

    def response(self, flow: http.HTTPFlow):
        if "/api/chat" in flow.request.path or "/api/generate" in flow.request.path:
            ACTIVE.dec()
            
            model = "unknown"
            status = "success" if 200 <= flow.response.status_code < 300 else "error"

            try:
                # With stream=False, it returns a single JSON object.
                if flow.response.content:
                    data = json.loads(flow.response.content)
                    model = data.get("model", "unknown")
                    
                    if "eval_count" in data:
                        TOKENS.labels(model=model).inc(data["eval_count"])
                    
                    if "total_duration" in data:
                        # total_duration is in nanoseconds in Ollama
                        duration_sec = data["total_duration"] / 1e9
                        LATENCY.labels(model=model).observe(duration_sec)
                        
            except Exception as e:
                logging.error(f"Failed to parse ollama metric payload: {e}")
                
            REQUESTS.labels(model=model, status=status).inc()

addons = [
    OllamaMetricsAddon()
]
