
#!/bin/bash
set -e

APP_DIR="/home/khadas/arxiv_assistant"
MOUNT_ROOT="/media/khadas/External1"
DATA_DIR="$MOUNT_ROOT/PDFs/Arxiv Assistant"
IMG_PATH="$DATA_DIR/pg_storage.img"
TARGET_PG_DIR="$DATA_DIR/postgres"
DEV="/dev/sda2"

# 1. Mount External
sudo mkdir -p "$MOUNT_ROOT"
if ! mountpoint -q "$MOUNT_ROOT"; then
    echo "Mounting Drive..."
    sudo mount "$DEV" "$MOUNT_ROOT" || echo "Mount failed (maybe already mounted)"
fi

# 2. Mount Official Database Image
IMG_PATH="/media/khadas/External1/postgres.img"
TARGET_PG_DIR="/home/khadas/arxiv_assistant/postgres_mount"

sudo mkdir -p "$TARGET_PG_DIR"
if ! mountpoint -q "$TARGET_PG_DIR"; then
    echo "Mounting Official DB Image..."
    sudo mount -o loop "$IMG_PATH" "$TARGET_PG_DIR" || echo "Loop mount failed"
    sudo chown -R 1000:1000 "$TARGET_PG_DIR"
fi

# 3. Start Docker (if not running)
sudo systemctl start docker

# 4. Patch Database
echo "Patching Database..."
# Wait for DB container
until sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c '\q' 2>/dev/null; do
  echo "Waiting for DB..."
  sleep 5
done

# Run alter commands
sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c 'ALTER TABLE papers ADD COLUMN IF NOT EXISTS is_downloaded BOOLEAN DEFAULT FALSE;'
sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c 'ALTER TABLE papers ADD COLUMN IF NOT EXISTS extracted_abstract TEXT;'
sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c 'ALTER TABLE papers ADD COLUMN IF NOT EXISTS extracted_introduction TEXT;'
sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c 'CREATE EXTENSION IF NOT EXISTS vector;'
sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c 'ALTER TABLE papers ADD COLUMN IF NOT EXISTS abstract_embedding vector(768);'
sudo docker exec arxiv_assistant_db psql -U user -d arxiv_db -c 'ALTER TABLE papers ADD COLUMN IF NOT EXISTS introduction_embedding vector(768);'

echo "Schema Patched."

# 5. Check Queue File (Generated by python script earlier)
QUEUE_FILE="$DATA_DIR/benchmark_queue.json"
if [ ! -f "$QUEUE_FILE" ]; then
    echo "Queue file missing! Attempting to generate..."
    if [ -f "$APP_DIR/backend/prepare_benchmark_host.py" ]; then
        sudo python3 "$APP_DIR/backend/prepare_benchmark_host.py" "$DATA_DIR"
        sudo chown 1000:1000 "$QUEUE_FILE"
    fi
fi

# 6. Run Benchmark
echo "Starting Benchmark..."
sudo docker restart arxiv_assistant_worker
sudo docker exec -d arxiv_assistant_worker python collect_metrics.py

echo "Benchmark Started."
